// Função para somar dois números
function soma(a, b) {
    return a + b;
}

// Função para subtrair dois números
function subtracao(a, b) {
    return a - b;
}

// Testando as funções
let numero1 = 10;
let numero2 = 5;

console.log("Soma: " + soma(numero1, numero2)); // Saída: Soma: 15
console.log("Subtração: " + subtracao(numero1, numero2)); // Saída: Subtração: 5